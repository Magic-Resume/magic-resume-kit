import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { root } from './packages.mjs';
const artifacts = JSON.parse(readFileSync(join(root, '.artifacts/manifest.json'), 'utf8'));
const dir = mkdtempSync(join(tmpdir(), 'magic-kit-consumer-'));
const mcpDir = mkdtempSync(join(tmpdir(), 'magic-kit-mcp-'));
const env = {...Object.fromEntries(Object.entries(process.env).filter(([key]) => !/^(?:npm_config_|npm_package_|pnpm_|node_auth_token$|npm_token$)/i.test(key))), NPM_CONFIG_USERCONFIG: join(dir, '.npmrc'), NPM_CONFIG_REGISTRY: 'https://registry.npmjs.org/'};
delete env.NODE_AUTH_TOKEN; delete env.NPM_TOKEN;
writeFileSync(join(dir, '.npmrc'), 'registry=https://registry.npmjs.org/\n@magic-resume-kit:registry=https://registry.npmjs.org/\n');
writeFileSync(join(dir, 'package.json'), JSON.stringify({private: true, type: 'module'}));
try {
  execFileSync('npm', ['install', '--ignore-scripts', '--no-audit', '--no-fund', ...artifacts.map(p => p.file), 'react@19.2.3', 'react-dom@19.2.3', 'react-i18next@15.7.4', 'i18next@25.8.4', 'typescript@5.9.3', '@types/react@19', '@types/react-dom@19'], {cwd: dir, env, stdio: 'inherit'});
  writeFileSync(join(dir, 'smoke.mjs'), `
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { templateIds, defaultResume } from '@magic-resume-kit/resume-schema';
import { getTemplateManifestList } from '@magic-resume-kit/resume-templates/registry';
import { Button } from '@magic-resume-kit/design-system';
import { Calendar, Server, Smartphone } from '@magic-resume-kit/icons';
import { cn } from '@magic-resume-kit/utils';
import { applyResumePatch } from '@magic-resume-kit/mcp';
const require = createRequire(import.meta.url);
assert.equal(getTemplateManifestList().length, templateIds.length);
assert.ok(defaultResume && typeof applyResumePatch === 'function');
assert.match(renderToStaticMarkup(React.createElement(Button, null, 'Save')), /<button/);
assert.match(renderToStaticMarkup(React.createElement(Calendar)), /<svg/);
assert.ok(Server && Smartphone);
assert.equal(cn('p-2', 'p-4'), 'p-4');
for (const suffix of ['','/core','/dom','/server','/TemplateCustomizer','/config','/config/defaults','/config/magic-templates','/renderer/MagicResumeRenderer','/renderer/EditableCanvas','/pdf/browser','/pdf/charset','/registry','/types/magic-dsl','/types/resume']) await import('@magic-resume-kit/resume-templates' + suffix);
for (const suffix of ['/react','/recipes','/cx']) await import('@magic-resume-kit/design-system' + suffix);
for (const file of ['tokens.css','utilities.css','motion.css']) assert.ok(readFileSync(require.resolve('@magic-resume-kit/design-system/styles/' + file), 'utf8').length > 0);
assert.ok(JSON.parse(readFileSync(require.resolve('@magic-resume-kit/resume-schema/schema.json'), 'utf8')).properties);
console.log('Clean consumer: imports, rendering, template IDs, JSON Schema and styles passed.');
`);
  execFileSync(process.execPath, ['smoke.mjs'], {cwd: dir, env, stdio: 'inherit'});
  writeFileSync(join(dir, 'types.ts'), `import type { Resume } from '@magic-resume-kit/resume-schema';\nimport { compile } from '@magic-resume-kit/resume-templates/core';\nimport { Button } from '@magic-resume-kit/design-system';\nimport { cn } from '@magic-resume-kit/utils';\nimport { createApiClient } from '@magic-resume-kit/mcp';\nconst consume = (resume: Resume) => [resume, compile, Button, cn, createApiClient];\nvoid consume;\n`);
  execFileSync(process.execPath, ['node_modules/typescript/bin/tsc', '--noEmit', '--strict', '--skipLibCheck', '--module', 'NodeNext', '--moduleResolution', 'NodeNext', '--target', 'ES2022', 'types.ts'], {cwd: dir, env, stdio: 'inherit'});
  const help = execFileSync(process.execPath, ['node_modules/@magic-resume-kit/mcp/dist/cli.js', '--help'], {cwd: dir, env, encoding: 'utf8'});
  assert.match(help, /magic-resume/i);
  console.log('Clean consumer: declarations and MCP CLI passed without private registry credentials.');
  writeFileSync(join(mcpDir, 'package.json'), JSON.stringify({private: true, type: 'module'}));
  writeFileSync(join(mcpDir, '.npmrc'), 'registry=https://registry.npmjs.org/\n');
  const mcpEnv = {...env, NPM_CONFIG_USERCONFIG: join(mcpDir, '.npmrc')};
  const mcpTarball = artifacts.find(pkg => pkg.name === '@magic-resume-kit/mcp').file;
  execFileSync('npm', ['install', '--ignore-scripts', '--no-audit', '--no-fund', mcpTarball], {cwd: mcpDir, env: mcpEnv, stdio: 'inherit'});
  execFileSync(process.execPath, ['--input-type=module', '-e', `import { createRequire } from 'node:module'; import assert from 'node:assert/strict'; const require=createRequire(import.meta.url); for (const name of ['react','next','@react-pdf/renderer']) assert.throws(() => require.resolve(name)); const mcp=await import('@magic-resume-kit/mcp'); assert.equal(typeof mcp.applyResumePatch,'function');`], {cwd: mcpDir, env: mcpEnv, stdio: 'inherit'});
  assert.match(execFileSync(join(mcpDir, 'node_modules/.bin/magic-resume'), ['--help'], {cwd: mcpDir, env: mcpEnv, encoding: 'utf8'}), /magic-resume mcp/);
  console.log('Standalone MCP installs and starts without React, Next.js or PDF dependencies.');
} finally { rmSync(dir, {recursive: true, force: true}); rmSync(mcpDir, {recursive: true, force: true}); }
